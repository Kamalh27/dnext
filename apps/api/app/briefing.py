_NUM = re.compile(r"\d[\d,]*\.?\d*")


def _numbers(s: str) -> list[str]:
    return [m.rstrip(".").replace(",", "") for m in _NUM.findall(s)]


def _polish(md: str) -> str:
    """Optional LLM rewording of prose. Disabled unless BRIEFING_MODEL set and backend != mock.
    Any change to the multiset of numbers => discard the LLM output and keep the template."""
    s = settings()
    if not s.briefing_model or s.geo_backend == "mock":
        return md
    try:
        from google import genai
        client = genai.Client(vertexai=True, project=s.project_id, location="global")
        resp = client.models.generate_content(
            model=s.briefing_model,
            contents="Polish the wording of this briefing for clarity. Keep ALL numbers, tables, headings, "
                     "caveats and language exactly as is. Do not add facts.\n\n" + md)
        new = (resp.text or "").strip()
        if new and sorted(_numbers(new)) == sorted(_numbers(md)):
            return new + "\n"
        log.warning("LLM polish changed numbers; using template")
    except Exception as e:
        log.warning("LLM polish failed: %s", e)
    return md


def to_html(md: str, language: str = "en", auto_print: bool = False) -> str:
    """Minimal markdown->HTML (headings, bullets, tables, quotes, bold/italic) for the browser's Save as PDF."""
    def inline(s: str) -> str:
        s = _html.escape(s)
        s = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
        s = re.sub(r"(?<![\w])_(.+?)_(?![\w])", r"<i>\1</i>", s)
        return re.sub(r"(https?://[^\s<)]+)", r'<a href="\1">\1</a>', s)

    body, lines, i = [], md.split("\n"), 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                if not set(lines[i]) <= set("|-: "):
                    rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            head, rest = rows[0], rows[1:]
            body.append("<table><thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead><tbody>"
                        + "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in rest)
                        + "</tbody></table>")
            continue
        if m := re.match(r"(#{1,3}) (.*)", ln):
            body.append(f"<h{len(m[1])}>{inline(m[2])}</h{len(m[1])}>")
        elif ln.startswith("- "):
            items = []
            while i < len(lines) and lines[i].startswith("- "):
                items.append(f"<li>{inline(lines[i][2:])}</li>"); i += 1
            body.append("<ul>" + "".join(items) + "</ul>")
            continue
        elif ln.startswith("> "):
            body.append(f"<blockquote>{inline(ln[2:])}</blockquote>")
        elif ln.strip():
            body.append(f"<p>{inline(ln)}</p>")
        i += 1
    th = language == "th"
    css = ("@page{size:A4;margin:16mm}"
           "body{font-family:'Noto Sans Thai','Sarabun',system-ui,-apple-system,'Segoe UI',sans-serif;max-width:820px;margin:0 auto;padding:1.5rem 1rem 3rem;"
           "color:#14211b;line-height:1.55;font-size:14px}"
           "h1{font-size:1.6rem;margin:.2rem 0 .4rem;border-bottom:3px solid #1f6f50;padding-bottom:.4rem}"
           "h2{font-size:1.15rem;margin:1.5rem 0 .4rem;color:#1f6f50;break-after:avoid}h3{font-size:1rem;margin:1rem 0 .2rem;break-after:avoid}"
           "table{border-collapse:collapse;width:100%;margin:.5rem 0;font-size:13px}th,td{border:1px solid #b9c4bd;padding:4px 8px;text-align:left;vertical-align:top}"
           "th{background:#e8f0ec}tr{break-inside:avoid}ul{padding-left:1.2rem;margin:.3rem 0}li{margin:.15rem 0}"
           "blockquote{border-left:4px solid #bd0026;margin:.5rem 0;padding:.25rem 1rem;background:#fff3f3}"
           ".bar{display:flex;justify-content:space-between;align-items:center;gap:1rem;margin-bottom:1rem;color:#4d5f56;font-size:12px}"
           "button{font:inherit;padding:.45rem .9rem;border:1px solid #1f6f50;background:#1f6f50;color:#fff;border-radius:6px;cursor:pointer}"
           "@media print{.bar button{display:none}body{padding:0;max-width:none}a{color:inherit;text-decoration:none}}")
    bar = ('<div class="bar"><span>DNext</span><button onclick="window.print()">'
           + ("บันทึกเป็น PDF" if th else "Save as PDF") + "</button></div>")
    script = "<script>addEventListener('load',function(){setTimeout(function(){window.print()},400)})</script>" if auto_print else ""
    title = _html.escape(next((ln[2:] for ln in md.split("\n") if ln.startswith("# ")), "DNext report"))
    return (f'<!doctype html><html lang="{language}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            f"<title>{title}</title><style>{css}</style></head><body>{bar}" + "\n".join(body) + f"{script}</body></html>")
