def _n(v, dec: int = 0) -> str:
    return f"{v:,.{dec}f}"


def _cell(s) -> str:
    return str(s).replace("|", "/").replace("\n", " ")


def build_briefing(r: dict, language: str = "en") -> str:
    t = L["th" if language == "th" else "en"]
    th = language == "th"
    a, h, x = r["area"], r["hazard"], r["exposure"]
    name = f"{a['name_th']} ({a['name']})" if th and a.get("name_th") else a["name"]
    ap = t["approx"]
    out = [f"# {t['title']}: {name}", ""]
    sources = sorted(set(h.get("data_sources", []) + x.get("data_sources", [])))
    if any("mock" in s.lower() for s in sources):
        out += [f"> **{t['synthetic']}**", ""]
    out += [f"## {t['scenario']}", "", f"- {t['area']}: {name}"]
    fc = r.get("forecast")
    if fc:
        out += [f"- {t['obs_fc']}: {_n(fc['observed_rain_mm'], 1)} + {_n(fc['forecast_rain_mm'], 1)} mm "
                f"({_n(fc['horizon_days'])} {t['days']})",
                f"- {t['model_run']}: {fc['model_run_time']}"]
    else:
        out += [f"- {t['rain']}: {_n(r['rainfall_mm'])} mm", f"- {t['dur']}: {_n(r['duration_h'])} {t['hours']}"]
    if h.get("antecedent_mm") is not None:
        out.append(f"- {t['ante'].format(days=h.get('antecedent_days', ''))}: {_n(h['antecedent_mm'], 1)} mm")
    out += ["", f"## {t['headline']}", ""]
    for key, v, dec in (("people", x["people"], 0), ("hh", x["households_est"], 0), ("bld", x["buildings"], 0),
                        ("road", x["road_km"], 1), ("sch", x["schools"], 0), ("hosp", x["hospitals"], 0)):
        out.append(f"- {t[key]}: {ap}{_n(v, dec)}")
    if x.get("shelters") is not None:
        out.append(f"- {t['shel']}: {_n(x['shelters'])}")
    out += ["", f"## {t['top']}", "", f"| # | {t['unit']} | {t['ppl']} | {t['bldc']} | {t['roadc']} |",
            "|---|---|---|---|---|"]
    for i, u in enumerate(x["top_admin_units"][:10], 1):
        un = u.get("name_th") if th and u.get("name_th") else u["name"]
        out.append(f"| {i} | {_cell(un)} | {ap}{_n(u['people'])} | "
                   f"{ap}{_n(u['buildings']) if 'buildings' in u else '-'} | "
                   f"{ap}{_n(u['road_km'], 1) if 'road_km' in u else '-'} |")
    named = [f for f in x.get("facilities") or [] if "risk" in f]
    if named:
        counts = x.get("facilities_named") or {}
        shown = named[:FACILITY_ROWS]
        out += ["", f"## {t['fac']}", "", t["fac_count"].format(h=counts.get("hospitals", 0), s=counts.get("schools", 0), n=len(shown)), "",
                f"| # | {t['fac_name']} | {t['fac_type']} | {t['fac_tambon']} | {t['fac_risk']} | {t['fac_class']} |", "|---|---|---|---|---|---|"]
        for i, f in enumerate(shown, 1):
            nm = (f.get("name_th") if th and f.get("name_th") else f["name"])
            tb = (f.get("tambon_th") if th and f.get("tambon_th") else f["tambon"])
            cl = f.get("risk_class_name_th") if th else f.get("risk_class_name")
            out.append(f"| {i} | {_cell(nm)} | {t['kind'].get(f['kind'], f['kind'])} | {_cell(tb)} | {_n(f['risk'], 1)} | {_cell(cl or '-')} |")
        out += ["", f"_{t['fac_note']}_"]
    g = guidance.sections(r, language)
    out += ["", f"## {g['title']}", "", f"_{g['note']}_"]
    for heading, bullets in g["sections"]:
        out += ["", f"### {heading}", ""] + [f"- {b}" for b in bullets]
    out += ["", f"## {t['assume']}", "", f"- {t['a_rain']}"]
    if x.get("household_size_assumed"):
        out.append("- " + t["a_hh"].format(hs=x["household_size_assumed"]))
    out += ["- " + t["a_res"].format(res=h.get("resolution_m", x.get("resolution_m", "?"))),
            "- " + t["a_date"].format(d=h.get("date_of_data", "?"))]
    out += ["", f"## {t['limits']}", ""] + [f"- {_cell(s)}" for s in dict.fromkeys(h.get("limitations", []) + x.get("limitations", []))]
    out += ["", f"## {t['sources']}", ""] + [f"- {_cell(s)}" for s in sources]
    out += ["", f"## {t['note']}", "", t["note_txt"], "", f"_{t['generated']} | scenario {r['scenario_id']}_", ""]
    md = "\n".join(out)
    return _polish(md)


